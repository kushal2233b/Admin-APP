/**
 * Resolves a high-quality locally saved category banner image for a given category/game name.
 */
export function getCategoryBannerImage(categoryOrGameName?: string, categoriesList?: any[]): string {
  if (!categoryOrGameName) {
    return CATEGORY_BANNER_IMAGES['FREE FIRE'] || getFallbackBannerSvg('FREE FIRE');
  }

  const raw = String(categoryOrGameName).trim();
  const upper = raw.toUpperCase();

  // 1. Check if category exists in Firestore categories list with a custom imageUrl/bannerUrl
  if (categoriesList && Array.isArray(categoriesList)) {
    const found = categoriesList.find(
      (c) => c && (c.id === raw || c.name === raw || (c.name && c.name.toUpperCase() === upper))
    );
    if (found && (found.imageUrl || found.bannerUrl)) {
      const catImg = found.imageUrl || found.bannerUrl;
      if (catImg && catImg !== 'N/A' && catImg.trim().length > 0) {
        return catImg.trim();
      }
    }
  }

  // 2. Direct exact match in CATEGORY_BANNER_IMAGES
  if (CATEGORY_BANNER_IMAGES[upper]) {
    return CATEGORY_BANNER_IMAGES[upper];
  }

  // 3. Substring matching for category name
  if (upper.includes('FREE FIRE') || upper.includes('FF')) {
    return CATEGORY_BANNER_IMAGES['FREE FIRE'];
  }
  if (upper.includes('BGMI') || upper.includes('BATTLEGROUNDS') || upper.includes('PUBG')) {
    return CATEGORY_BANNER_IMAGES['BGMI'];
  }
  if (upper.includes('CALL OF DUTY') || upper.includes('COD') || upper.includes('WARZONE')) {
    return CATEGORY_BANNER_IMAGES['CALL OF DUTY'];
  }
  if (upper.includes('LUDO')) {
    return CATEGORY_BANNER_IMAGES['LUDO'];
  }
  if (upper.includes('CLASH ROYALE') || upper.includes('CLASH OF CLANS')) {
    return CATEGORY_BANNER_IMAGES['CLASH ROYALE'];
  }
  if (upper.includes('VALORANT')) {
    return CATEGORY_BANNER_IMAGES['VALORANT'];
  }
  if (upper.includes('CS') || upper.includes('COUNTER')) {
    return CATEGORY_BANNER_IMAGES['CS:GO'];
  }
  if (upper.includes('FIFA') || upper.includes('EA') || upper.includes('FOOTBALL')) {
    return CATEGORY_BANNER_IMAGES['FIFA'];
  }
  if (upper.includes('CRICKET') || upper.includes('WCC')) {
    return CATEGORY_BANNER_IMAGES['CRICKET'];
  }
  if (upper.includes('CHESS')) {
    return CATEGORY_BANNER_IMAGES['CHESS'];
  }
  if (upper.includes('CARROM')) {
    return CATEGORY_BANNER_IMAGES['CARROM'];
  }
  if (upper.includes('APEX')) {
    return CATEGORY_BANNER_IMAGES['APEX LEGENDS'];
  }

  // Fallback to Free Fire banner or SVG fallback
  return CATEGORY_BANNER_IMAGES['FREE FIRE'] || getFallbackBannerSvg(upper);
}

/**
 * React Image onError handler to cleanly replace broken image URLs with instant SVG fallback.
 */
export function handleImageFallback(e: React.SyntheticEvent<HTMLImageElement, Event>, label?: string) {
  const target = e.currentTarget;
  if (!target.dataset.triedFallback) {
    target.dataset.triedFallback = 'true';
    target.src = getFallbackBannerSvg(label || 'ESPORTS');
  }
}
